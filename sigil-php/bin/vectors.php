<?php

declare(strict_types=1);

/**
 * Regenerates fixtures/vectors.json at the repo root -- the contract every
 * language implementation in this repo is validated against.
 *
 * Run this whenever SegmentModel, Quadrant or the default geometry changes,
 * and commit the regenerated fixtures in the same change. Changing them is a
 * breaking change for every language implementation at once.
 *
 * Usage:
 *   php bin/vectors.php [--check] [path/to/vectors.json]
 *
 *   --check   exit 1 if the file on disk differs from what would be written,
 *             without touching it. Intended for CI.
 *
 * The default output path can also be set with SIGIL_FIXTURES.
 */

require __DIR__ . '/_bootstrap.php';

use Cistercian\Encoder;
use Cistercian\Quadrant;
use Cistercian\SegmentModel;

/**
 * Chosen to exercise every segment shape at least once (1, 6, 9 in the ones
 * place cover top, outer and the closed 9 box), every quadrant transform at
 * least once (10, 100, 1000), the empty case (0, stem only), and two
 * composites end to end (7323, 9999).
 */
const NUMBERS = [0, 1, 6, 9, 10, 100, 1000, 7323, 9999];

$argsList = array_slice($argv, 1);
$check = in_array('--check', $argsList, true);
$paths = array_values(array_filter($argsList, static fn (string $a): bool => !str_starts_with($a, '--')));

$target = $paths[0]
    ?? getenv('SIGIL_FIXTURES')
    ?: __DIR__ . '/../../fixtures/vectors.json';

$encoder = new Encoder();

$payload = [
    'note' => 'Generated by sigil-php bin/vectors.php. Do not hand-edit -- '
        . 'regenerate it from the digit map instead. Every implementation is '
        . '"spec-compliant" exactly when it reproduces these vectors.',
    'geometry' => [
        'stemHeight' => $encoder->stemHeight,
        'quadrantWidth' => $encoder->quadrantWidth,
        'stemX' => $encoder->stemX,
        'stemTopY' => $encoder->stemTopY,
    ],
    'quadrantOrder' => array_keys(Quadrant::ALL),
    'segmentOrder' => SegmentModel::KEYS,
    'vectors' => array_map(
        static fn (int $number): array => [
            'number' => $number,
            'digits' => $encoder->digitsOf($number),
            'stem' => $encoder->stem(),
            'segments' => $encoder->segmentsFor($number),
        ],
        NUMBERS,
    ),
];

$json = json_encode(
    $payload,
    JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR,
) . "\n";

if ($check) {
    $current = is_file($target) ? file_get_contents($target) : null;

    if ($current === $json) {
        fwrite(STDOUT, "vectors.json is up to date: {$target}\n");
        exit(0);
    }

    fwrite(STDERR, "vectors.json is STALE: {$target}\n");
    fwrite(STDERR, "Run `php sigil-php/bin/vectors.php` and commit the regenerated file.\n");
    exit(1);
}

$dir = dirname($target);

if (!is_dir($dir) && !mkdir($dir, 0o775, true) && !is_dir($dir)) {
    fwrite(STDERR, "Cannot create {$dir}\n");
    exit(1);
}

if (file_put_contents($target, $json) === false) {
    fwrite(STDERR, "Cannot write {$target}\n");
    exit(1);
}

$count = count(NUMBERS);
fwrite(STDOUT, "Wrote {$count} vectors to {$target}\n");
